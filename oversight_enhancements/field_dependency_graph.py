    # ── Traversal ─────────────────────────────────────────────────────────────

    def traverse(
        self,
        triggered_fields: Dict[str, Dict],
        extracted_values: Dict[str, float],
        materiality_floor: float = 1000.0,
        max_depth: int = 3,
    ) -> List[ChainedReviewPoint]:
        """
        Given a set of fields that have diffs, traverse the graph to find
        all downstream fields that are logically implicated.

        Args:
            triggered_fields: {field_name: {delta, value_a, value_b, severity, ...}}
            extracted_values:  All field values extracted from the documents
            materiality_floor: Minimum delta to trigger traversal
            max_depth:         Maximum chain depth to follow

        Returns:
            List of ChainedReviewPoint objects (deduplicated)
        """
        chained: List[ChainedReviewPoint] = []
        visited_pairs: Set[Tuple[str, str]] = set()

        def _traverse(trigger_field: str, trigger_info: Dict, depth: int) -> None:
            if depth > max_depth:
                return
            delta = abs(trigger_info.get("delta") or 0)
            if delta < materiality_floor and depth == 1:
                return

            for edge in self.edges:
                if edge.source != trigger_field:
                    continue
                # Skip edges with very low learned weight
                if edge.weight < 0.2:
                    continue
                pair = (trigger_field, edge.target)
                if pair in visited_pairs:
                    continue
                visited_pairs.add(pair)

                # Check conditional edges
                if edge.edge_type == EdgeType.CONDITIONAL and edge.condition:
                    if not self._evaluate_condition(
                        edge.condition, extracted_values, trigger_field
                    ):
                        continue

                # Build the chained review point
                cp = self._build_chained_point(
                    edge=edge,
                    trigger_field=trigger_field,
                    trigger_info=trigger_info,
                    extracted_values=extracted_values,
                    depth=depth,
                )
                if cp:
                    chained.append(cp)
                    # Recurse — downstream field may itself trigger further chains
                    next_info = {
                        "delta": trigger_info.get("delta"),
                        "value_a": extracted_values.get(edge.target),
                        "value_b": None,
                        "severity": cp.severity,
                    }
                    _traverse(edge.target, next_info, depth + 1)

        for field_name, info in triggered_fields.items():
            _traverse(field_name, info, depth=1)

        # Deduplicate by (trigger, chain_field)
        seen = set()
        unique = []
        for cp in chained:
            key = (cp.trigger_field, cp.chain_field)
            if key not in seen:
                seen.add(key)
                unique.append(cp)

        logger.info(
            "FieldDependencyGraph.traverse: %d triggers → %d chained points",
            len(triggered_fields), len(unique),
        )
        return unique

    def _evaluate_condition(
        self,
        condition: str,
        values: Dict[str, float],
        trigger_field: str,
    ) -> bool:
        """Evaluate a named condition against extracted values."""
        if condition == "reserves_negative":
            v = values.get("reserves") or values.get("profit_loss") or 0.0
            return v < 0
        if condition == "net_liabilities":
            assets = (values.get("fixed_assets") or 0) + (values.get("debtors") or 0) + (values.get("cash") or 0) + (values.get("stock") or 0)
            liabilities = (values.get("creditors") or 0) + (values.get("loans") or 0)
            return liabilities > assets
        if condition == "loans_due_within_one_year_material":
            loans = values.get("loans") or 0.0
            turnover = values.get("turnover") or 100_000.0
            return loans > (turnover * 0.1)  # >10% of turnover is material
        return True  # Unknown conditions default to triggered

    def _build_chained_point(
        self,
        edge: DependencyEdge,
        trigger_field: str,
        trigger_info: Dict,
        extracted_values: Dict[str, float],
        depth: int,
    ) -> Optional[ChainedReviewPoint]:
        """Construct a ChainedReviewPoint from an edge and trigger."""
        try:
            delta = trigger_info.get("delta") or 0.0
            value_a = trigger_info.get("value_a")
            value_b = trigger_info.get("value_b")
            direction = "increase" if delta > 0 else "decrease"

            # Fill description template
            template_vars = {
                "delta": abs(delta),
                "direction": direction,
                "trigger_value_a": value_a or 0.0,
                "trigger_value_b": value_b or 0.0,
                "chain_field": edge.target,
            }
            try:
                description = edge.description_template.format(**template_vars)
            except (KeyError, ValueError):
                description = edge.description_template

            # Severity — escalate if directed
            base_sev = trigger_info.get("severity", "medium")
            sev_order = ["low", "medium", "high", "critical"]
            if edge.severity_escalation == "escalate":
                idx = sev_order.index(base_sev) if base_sev in sev_order else 1
                severity = sev_order[min(idx + 1, 3)]
            elif edge.severity_escalation == "downgrade":
                idx = sev_order.index(base_sev) if base_sev in sev_order else 1
                severity = sev_order[max(idx - 1, 0)]
            else:
                severity = base_sev

            # Deeper chains are downgraded one level
            if depth > 1:
                idx = sev_order.index(severity) if severity in sev_order else 1
                severity = sev_order[max(idx - 1, 0)]

            return ChainedReviewPoint(
                trigger_field=trigger_field,
                chain_field=edge.target,
                edge_type=edge.edge_type,
                title=edge.review_template,
                description=description,
                frs_reference=edge.frs_reference,
                severity=severity,
                chain_depth=depth,
                trigger_delta=delta,
                trigger_value_a=value_a,
                trigger_value_b=value_b,
                shap_contribution=edge.weight,
                category="chained_relationship",
                recommended_action=(
                    f"Review the {edge.target} field in light of the {trigger_field} anomaly. "
                    f"Ref: {edge.frs_reference}"
                ),
            )
        except Exception as e:
            logger.warning("Failed to build chained point for edge %s→%s: %s",
                           trigger_field, edge.target, e)
            return None

    # ── Flywheel learning ─────────────────────────────────────────────────────

    def update_edge_weight(
        self,
        source: str,
        target: str,
        confirmed: bool,
    ) -> None:
        """
        Update edge weight based on partner confirmation.
        Called by flywheel when a chained review point is resolved.

        Bayesian-style update: weight moves toward 1.0 on confirmation,
        toward 0.0 on rejection, with dampening to prevent fast collapse.
        """
        for edge in self.edges:
            if edge.source == source and edge.target == target:
                if confirmed:
                    edge.confirmed_count += 1
                    # Increase weight toward 1.0, dampened
                    edge.weight = min(1.0, edge.weight + 0.05)
                else:
                    edge.rejected_count += 1
                    # Decrease weight toward 0.2 floor (never fully silence)
                    edge.weight = max(0.2, edge.weight - 0.05)
                logger.debug(
                    "Edge %s→%s weight updated to %.3f (confirmed=%d, rejected=%d)",
                    source, target, edge.weight, edge.confirmed_count, edge.rejected_count,
                )
                break

    def export_weights(self) -> List[Dict]:
        """Export edge weights for persistence in flywheel store."""
        return [
            {
                "source": e.source,
                "target": e.target,
                "weight": e.weight,
                "confirmed_count": e.confirmed_count,
                "rejected_count": e.rejected_count,
            }
            for e in self.edges
        ]

    def import_weights(self, weights: List[Dict]) -> None:
        """Restore learned edge weights from flywheel store."""
        weight_map = {(w["source"], w["target"]): w for w in weights}
        for edge in self.edges:
            key = (edge.source, edge.target)
            if key in weight_map:
                w = weight_map[key]
                edge.weight = w.get("weight", 1.0)
                edge.confirmed_count = w.get("confirmed_count", 0)
                edge.rejected_count = w.get("rejected_count", 0)
