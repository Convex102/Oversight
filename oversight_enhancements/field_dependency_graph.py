"""
OVERSIGHT LABS — Field Dependency Graph
========================================
Models accounting field relationships as a directed acyclic graph.
When a diff is detected on any node, the engine traverses downstream
dependents and auto-generates chained review points.

This is the core reasoning layer that separates Oversight from a diff tool.
No Paul Burns points are hardcoded — the graph encodes accounting identities
(e.g. retained_earnings = prior_retained + profit - dividends) which hold
universally under FRS102/FRS105. The specific values that violate those
identities are detected at runtime against the actual extracted data.

Integration points:
  - Called from _compare_and_raise() in engagements_routes AFTER diff rows
    are computed, before review points are written to DB.
  - Flywheel captures confirmed chain traversals to update edge weights.
  - SHAP scores are attached to each generated chained point.
"""

from __future__ import annotations

import logging
from dataclasses import dataclass, field
from typing import Dict, List, Optional, Set, Tuple, Any
import json

logger = logging.getLogger(__name__)


# ── Edge types ────────────────────────────────────────────────────────────────

class EdgeType:
    """Accounting identity relationship types."""
    IDENTITY     = "identity"      # A = B + C (strict)
    CONSTRAINED  = "constrained"   # A must not exceed B (e.g. dividends ≤ distributable reserves)
    DIRECTIONAL  = "directional"   # If A increases, B should also increase (ratio relationship)
    COMPLETENESS = "completeness"  # If A exists, B must also exist (disclosure chain)
    CONDITIONAL  = "conditional"   # B is required only when A meets a condition


@dataclass
class DependencyEdge:
    """A directed edge in the field dependency graph."""
    source: str                     # upstream field
    target: str                     # downstream field
    edge_type: str                  # EdgeType constant
    formula: Optional[str] = None   # e.g. "retained_earnings = profit + prior_retained - dividends"
    condition: Optional[str] = None # e.g. "net_liabilities_position"
    review_template: str = ""       # Template for generated review point title
    description_template: str = ""  # Template for description
    frs_reference: str = ""         # Regulatory reference
    severity_escalation: str = "same"  # "escalate" | "same" | "downgrade"
    weight: float = 1.0             # Learned from flywheel — starts at 1.0
    confirmed_count: int = 0        # Times this chain was confirmed by a partner
    rejected_count: int = 0         # Times partner said chain wasn't relevant


@dataclass
class ChainedReviewPoint:
    """A review point generated by graph traversal, not direct diff."""
    trigger_field: str          # The diff that triggered this chain
    chain_field: str            # The downstream field implicated
    edge_type: str
    title: str
    description: str
    frs_reference: str
    severity: str               # "critical" | "high" | "medium" | "low"
    chain_depth: int            # How many hops from the trigger
    trigger_delta: Optional[float]
    trigger_value_a: Optional[float]
    trigger_value_b: Optional[float]
    shap_contribution: float = 0.0   # Feature importance of trigger field
    category: str = "chained_relationship"
    recommended_action: str = ""
    requires_values: Dict[str, Any] = field(default_factory=dict)


class FieldDependencyGraph:
    """
    Directed acyclic graph of accounting field relationships.

    The graph encodes universal accounting identities for UK SME
    financial statements under FRS102/FRS105. It does NOT encode
    client-specific values or Paul Burns' findings — those are runtime
    inputs. The graph answers: "given that field X has an anomaly,
    which other fields are logically implicated?"

    Usage:
        graph = FieldDependencyGraph()
        chains = graph.traverse(trigger_fields, extracted_values)
        for cp in chains:
            # convert to ReviewPoint and write to DB
    """

    def __init__(self):
        self.edges: List[DependencyEdge] = []
        self.nodes: Set[str] = set()
        self._build_frs102_graph()

    # ── Graph construction ────────────────────────────────────────────────────

    def _add_edge(self, source: str, target: str, **kwargs) -> None:
        edge = DependencyEdge(source=source, target=target, **kwargs)
        self.edges.append(edge)
        self.nodes.add(source)
        self.nodes.add(target)

